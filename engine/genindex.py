#!/usr/bin/env python3
import os, sys
from mem_common import MEMORY_DIR, memory_files, parse_file, is_active

MIN_DESC = 25
INDEX_HEADER = "# Memory Index (auto-generated by genindex.py — do not edit by hand)\n\n"
ARCHIVE_HEADER = ("\n## Archive (superseded / archived — kept for audit, "
                  "excluded from default recall)\n\n")


def build_index(memdir=MEMORY_DIR):
    rows, archived, warnings = [], [], []
    for path in memory_files(memdir):          # already sorted by basename
        rel = os.path.basename(path)
        rec = parse_file(path)
        name = rec["name"] or rel[:-3]
        typ = rec["type"] or "?"
        desc = (rec["description"] or "").strip()
        if not rec["name"]: warnings.append(f"{rel}: missing name")
        if not rec["type"]: warnings.append(f"{rel}: missing type")
        if not desc: warnings.append(f"{rel}: missing description")
        elif len(desc) < MIN_DESC: warnings.append(f"{rel}: weak description (<{MIN_DESC} chars)")
        if is_active(rec):
            rows.append(f"- `{name}` ({typ}) — {desc} · `{rel}`")
        else:
            sup = f" → superseded by `{rec['superseded_by']}`" if rec.get("superseded_by") else ""
            archived.append(f"- `{name}` ({typ}, {rec['status']}){sup} — {desc} · `{rel}`")
    content = INDEX_HEADER + "\n".join(rows) + "\n"
    if archived:
        content += ARCHIVE_HEADER + "\n".join(archived) + "\n"
    return content, warnings


def main():
    content, warnings = build_index()
    out = os.path.join(MEMORY_DIR, "INDEX.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write(content)
    for w in warnings:
        print(f"[genindex] WARN {w}", file=sys.stderr)
    main_part, _, arch_part = content.partition("## Archive")
    n_active = sum(1 for l in main_part.splitlines() if l.startswith("- `"))
    n_arch = sum(1 for l in arch_part.splitlines() if l.startswith("- `"))
    tail = f", {n_arch} archived" if n_arch else ""
    print(f"[genindex] wrote {out}: {n_active} entries{tail}, {len(warnings)} warnings")


if __name__ == "__main__":
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    main()
